const patterns = {
  sanitizer: /^[x\+\-\d\.\/\(\)\*i]+$/,
  addition:
    /^((\-?\d*(?:\.\d+)?)?([+-]?\d*(?:\.\d+)?)i)([\+\-])((\-?\d*(?:\.\d+)?)?([+-]?\d*(?:\.\d+)?)i)$/,

  secondAddition: /^[+-]i[+-][+-]i$/,

  multiplication:
    /^(?:\((\-?\d*(?:\.\d+)?)(([+-]?\d*(?:\.\d+)?)i?)\))([\*\/]?)(?:\((\-?\d*(?:\.\d+)?)(([+-]?\d*(?:\.\d+)?)i?)\))$/,

  preMult:
    /^\((.+)\)([\*\/])\((.+)\)$/,

  sqrt:
    /^sqrt\(((\-?\d*(?:\.\d+)?)?([+-]?\d*(?:\.\d+)?)i)\)$/,

  // sin, cos, tan
  trig:
    /^(sin|cos|tan)\(((\-?\d*(?:\.\d+)?)?([+-]?\d*(?:\.\d+)?)i)\)$/,
};

export default patterns;